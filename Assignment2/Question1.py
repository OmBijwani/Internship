# Dictionary
student = {
    "name": "Om",
    "age": 20,
    "course": "Python"
}

print("Dictionary:", student)


student["city"] = "Jaipur"
student["age"] = 21

print("Updated Dictionary:", student)



#TUPLE 
numbers = (10, 20, 30, 40, 50)

print("Tuple:", numbers)


print("First Element:", numbers[0])
print("Length:", len(numbers))


#SET 
fruits = {"apple", "banana", "mango"}

print("Set:", fruits)


fruits.add("orange")
fruits.add("apple")   

print("Updated Set:", fruits)